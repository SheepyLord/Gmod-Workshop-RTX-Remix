CODES = ("zh-CN", "zh-TW", "ja", "ko", "fr", "ru")


def main():
    strings, _ = catalog.update()
    for index, code in enumerate(CODES, 1):
        path = Path(catalog.I18N) / (code + ".po")
        table = {e["msgid"]: (e["msgstr"], e["fuzzy"]) for e in catalog.read_po(path) if e["msgid"]}
        for row in ROWS:
            value = row[index]
            assert value and "?" not in value and "\ufffd" not in value, (code, row[0])
            table[row[0]] = (value, False)
        catalog.write_po(path, code, strings, table)
        path.read_bytes().decode("utf-8")
    catalog.check(complete=True)
    print(f"{len(ROWS)} messages x {len(CODES)} languages: UTF-8, question marks and completeness PASS")


if __name__ == "__main__":
    main()
